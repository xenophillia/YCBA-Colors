import { readdir, writeFile, mkdir, stat } from 'node:fs/promises';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { fileURLToPath } from 'node:url';
const run = promisify(execFile);
const folder = new URL('./images/', import.meta.url);
const entries = await readdir(folder, { withFileTypes: true });
const names = entries.filter(entry => entry.isFile() && /\.(jpe?g|png|webp|gif|avif|svg|tiff?)$/i.test(entry.name))
  .map(entry => entry.name).sort((a, b) => a.localeCompare(b, undefined, { numeric: true }));
const images = [];
for (const name of names) {
  let path = './images/' + encodeURIComponent(name);
  if (/\.tiff?$/i.test(name)) {
    // TIFF support varies by browser; retain originals and generate JPEG previews.
    await mkdir(new URL('.gallery/', folder), { recursive: true });
    const source = new URL(encodeURIComponent(name), folder);
    const preview = new URL('.gallery/' + encodeURIComponent(name + '.jpg'), folder);
    const existing = await stat(preview).catch(() => undefined);
    if (!existing || existing.mtimeMs < (await stat(source)).mtimeMs) {
      await run('sips', ['-s', 'format', 'jpeg', '-Z', '1600', fileURLToPath(source), '--out', fileURLToPath(preview)]);
    }
    path = './images/.gallery/' + encodeURIComponent(name + '.jpg');
  }
  images.push(path);
}
await writeFile(new URL('./gallery-images.mjs', import.meta.url),
  '// Generated by node sync-images.mjs.\nexport const galleryImages = ' + JSON.stringify(images, null, 2) + ';\n');
console.log(`Gallery updated: ${images.length} images.`);
